/* Touch controls (Android, or desktop with C2_TOUCH=1).
 *  - menus: the screen is a mouse (touch = move the pointer and click)
 *  - races: on-screen buttons mapped to the game's default keys
 *      left:  steer left / right, repair, recover
 *      right: accelerate, brake/reverse, handbrake, use power-up, next power-up,
 *             BUY coin: fans out buy Armour / Power / Offensive (slide and release, or tap then tap)
 *      top-right: Esc (pause menu)
 *  - hidden while a game controller is in use (touch_gamepad), back on the next touch
 * Button artwork: platform/touch_atlas.h, generated by tools/make_touch_atlas.py.
 * "Race" is detected from the renderer: a frame that draws depth-buffered 3D geometry. */
#include <math.h>
#include <stdlib.h>
#include <string.h>
#include "plat.h"
#include "../win32/win32.h"
#include <zlib.h>
#include "touch_atlas.h"

extern void dinput_key(int, int);
extern int dinput_from_sdl(int);
extern int glide_in_3d(void);
extern int game_racing(void);
/* a race: 3D on screen and the game's race loop running (menus and the wrecks gallery draw 3D too) */
static int in_race(void) { return glide_in_3d() && game_racing(); }
extern int glide_to_game(float sx, float sy, int *gx, int *gy);

/* kind: 0 = hold button, 1 = BUY coin (opens the fan), 2 = fan item (only while the fan is open) */
typedef struct { float x, y, r; int sc; int art; int race_only; int kind; } Btn;
enum { NB = 14, B_COIN = 7, FAN_FIRST = 11 };
static Btn btns[NB];
static float scr_a = 16.0f / 9.0f;
static int visible;
/* a game controller is in use: the touch buttons are hidden until the screen is touched again */
static int pad_mode;
/* performance readout (three-finger tap toggles it; C2_PERF=1 on desktop) */
static int perf_on;
extern void glide_perf(float *fps, float *game, float *gl, float *swap);
static GLuint prog, vbo, vao;
static GLint u_col, u_sc;

typedef struct { SDL_FingerID id; int active; int btn; int btn2; int mouse; } Finger;   /* btn2: chord partner */
static Finger fingers[10];
static int held[NB];
static int fan_open;             /* BUY fan shown */
static Uint32 fan_until;         /* auto-close time (ms) */
static int fan_hover = -1;       /* fan item under a finger that slid off the coin */
static int fan_force;            /* C2_FANOPEN=1: keep the fan open (screenshots) */

static void press(int b, int down) {
    if (b < 0 || !btns[b].sc) return;
    if ((down && held[b] == 0) || (!down && held[b] == 1)) LOG("touch %s %s", SDL_GetScancodeName(btns[b].sc), down ? "down" : "up");
    if (down) { if (held[b]++ == 0) { dinput_key(dinput_from_sdl(btns[b].sc), 1); if (btns[b].sc == SDL_SCANCODE_ESCAPE) user32_key_event(0x1B, 1); } }
    else if (held[b] > 0 && --held[b] == 0) { dinput_key(dinput_from_sdl(btns[b].sc), 0); if (btns[b].sc == SDL_SCANCODE_ESCAPE) user32_key_event(0x1B, 0); }
}

static void layout(void) {
    int w, h;
    plat_drawable_size(&w, &h);
    if (w <= 0 || h <= 0) return;
    float a = (float)w / h;   /* coordinates: y in [0,1], x in [0,a] */
    scr_a = a;
    btns[0]  = (Btn){0.17f,     0.80f, 0.13f,  SDL_SCANCODE_KP_4,         TA_LEFT,      1, 0};
    btns[1]  = (Btn){0.47f,     0.80f, 0.13f,  SDL_SCANCODE_KP_6,         TA_RIGHT,     1, 0};
    /* right side; the bottom-right corner stays clear for the head-up map */
    btns[2]  = (Btn){a - 0.21f, 0.69f, 0.13f,  SDL_SCANCODE_KP_8,         TA_GAS,       1, 0};
    btns[3]  = (Btn){a - 0.47f, 0.84f, 0.10f,  SDL_SCANCODE_KP_2,         TA_BRAKE,     1, 0};
    /* handbrake: same direction from gas as before, at the same 0.23 distance as use power-up */
    btns[4]  = (Btn){a - 0.149f, 0.468f, 0.08f, SDL_SCANCODE_SPACE,       TA_HAND,      1, 0};
    /* use power-up: in the notch between gas and brake, 0.23 from both centres, so a thumb can hold
       gas and use together (nitrous needs throttle); the touch zone shared by both presses both */
    btns[5]  = (Btn){a - 0.253f, 0.916f, 0.075f, SDL_SCANCODE_LALT,       TA_USE,       1, 0};
    btns[6]  = (Btn){a - 0.40f, 0.52f, 0.06f,  SDL_SCANCODE_RIGHTBRACKET, TA_NEXT,      1, 0};
    btns[7]  = (Btn){a - 0.23f, 0.10f, 0.055f, 0,                         TA_COIN,      1, 1};   /* BUY coin, next to pause */
    /* repair and recover: under the head-up map (top-left corner, HUD pixels 4..136 x 4..120 of 480,
       see win32/glide.c), as far below it as the steering arrows are above the bottom of the screen
       (0.07), with the same gap between the two; clear of the camera cutout on the left edge */
    {
        const float map_l = 4 / 480.0f, map_b = 120 / 480.0f, gap = 1.0f - (0.80f + 0.13f), r = 0.065f;
        btns[8] = (Btn){map_l + r, map_b + gap + r, r, SDL_SCANCODE_BACKSPACE, TA_REPAIR,  1, 0};
        btns[9] = (Btn){map_l + 3 * r + gap, map_b + gap + r, r, SDL_SCANCODE_INSERT, TA_RECOVER, 1, 0};   /* same gap between them */
    }
    btns[10] = (Btn){a - 0.09f, 0.10f, 0.055f, SDL_SCANCODE_ESCAPE,       TA_PAUSE,     0, 0};
    /* the BUY fan: on a circle around the coin, opening to the lower left, all equally spaced
       (radius 0.17 from the coin, 48 degrees apart: 0.138 between neighbours) */
    static const int fan_sc[3] = {SDL_SCANCODE_DELETE, SDL_SCANCODE_END, SDL_SCANCODE_PAGEDOWN};
    static const int fan_art[3] = {TA_ARMOUR, TA_POWER, TA_OFFENSIVE};
    for (int i = 0; i < 3; i++) {
        float t = (195.0f + 48.0f * i) * 3.14159265f / 180.0f;
        btns[11 + i] = (Btn){btns[B_COIN].x + 0.17f * cosf(t), btns[B_COIN].y - 0.17f * sinf(t), 0.06f,
                             fan_sc[i], fan_art[i], 1, 2};
    }
}

static int hit(float x, float y, int race) {
    int best = -1; float bd = 1e9f;
    for (int i = 0; i < NB; i++) {
        if (btns[i].race_only && !race) continue;
        if (btns[i].kind == 2 && !fan_open) continue;
        float dx = x - btns[i].x, dy = y - btns[i].y, d = sqrtf(dx * dx + dy * dy);
        if (d < btns[i].r * 1.25f && d < bd) { bd = d; best = i; }
    }
    return best;
}

/* gas + use power-up and gas + handbrake form chords: a touch inside both buttons' touch zones
   (where they meet) presses both */
enum { B_GAS = 2, B_HAND = 4, B_USE = 5 };
static int chord_of(int b, float x, float y) {
    int cand[2], n = 0;
    if (b == B_GAS) { cand[n++] = B_USE; cand[n++] = B_HAND; }
    else if (b == B_USE || b == B_HAND) cand[n++] = B_GAS;
    for (int i = 0; i < n; i++) {
        int o = cand[i];
        float dx = x - btns[o].x, dy = y - btns[o].y;
        if (sqrtf(dx * dx + dy * dy) < btns[o].r * 1.25f) return o;
    }
    return -1;
}
static void set_chord(Finger *f, int c) {
    if (c == f->btn2) return;
    press(f->btn2, 0); f->btn2 = c; press(c, 1);
}

void touch_init(void) {
    perf_on = getenv("C2_PERF") != NULL;
    fan_force = getenv("C2_FANOPEN") != NULL;
#ifdef __ANDROID__
    visible = 1;
#else
    visible = getenv("C2_TOUCH") != NULL;
#endif
    layout();
}

static void release_all(void) {
    for (int i = 0; i < 10; i++) if (fingers[i].active) {
        if (fingers[i].btn2 >= 0) { press(fingers[i].btn2, 0); fingers[i].btn2 = -1; }
        if (fingers[i].btn >= 0) { press(fingers[i].btn, 0); fingers[i].btn = -1; }
    }
}

/* called by the platform layer: active = a controller was connected or used (1), or the last one removed (0) */
void touch_gamepad(int active) {
    if (active && !pad_mode) { release_all(); LOG("controller in use: touch controls hidden"); }
    if (!active && pad_mode) LOG("touch controls shown");
    pad_mode = active;
}

void touch_event(SDL_Event *e) {
    if (!visible) return;
    layout();
    float x = e->tfinger.x * scr_a, y = e->tfinger.y;
    int race = in_race();
    int slot = -1;
    for (int i = 0; i < 10; i++) if (fingers[i].active && fingers[i].id == e->tfinger.fingerId) slot = i;
    if (e->type == SDL_FINGERDOWN) {
        int nact = 0; for (int i = 0; i < 10; i++) nact += fingers[i].active;
        if (nact == 2) { perf_on = !perf_on; LOG("performance readout %s", perf_on ? "on" : "off"); }
        if (slot < 0) for (int i = 0; i < 10; i++) if (!fingers[i].active) { slot = i; break; }
        if (slot < 0) return;
        Finger *f = &fingers[slot];
        f->active = 1; f->id = e->tfinger.fingerId;
        f->btn = -1; f->btn2 = -1; f->mouse = 0;
        if (pad_mode) {
            touch_gamepad(0);
            if (race) return;           /* in a race the first touch only brings the buttons back */
        }
        f->btn = hit(x, y, race);
        if (f->btn == B_COIN) { fan_open = !fan_open; fan_until = SDL_GetTicks() + 3000; fan_hover = -1; return; }
        if (fan_open && (f->btn < 0 || btns[f->btn].kind != 2)) fan_open = 0;   /* a touch elsewhere closes it */
        if (f->btn >= 0 && btns[f->btn].kind == 2) fan_until = SDL_GetTicks() + 400;  /* buy, then close */
        if (perf_on && y < 0.07f && x < 1.0f) { plat_cycle_fps_cap(); f->btn = -1; return; }   /* tap the readout: next frame rate cap */
        if (f->btn >= 0) { press(f->btn, 1); set_chord(f, chord_of(f->btn, x, y)); return; }
        if (!race) {
            /* menus: the touch is the mouse */
            int gx, gy;
            if (glide_to_game(e->tfinger.x, e->tfinger.y, &gx, &gy)) {
                user32_mouse_event(gx, gy, 0, 0);
                user32_mouse_event(gx, gy, 1, 1);
                f->mouse = 1;
            }
        }
    } else if (slot >= 0) {
        Finger *f = &fingers[slot];
        int gx, gy;
        if (e->type == SDL_FINGERMOTION) {
            if (f->mouse) { if (glide_to_game(e->tfinger.x, e->tfinger.y, &gx, &gy)) user32_mouse_event(gx, gy, 1, 0); return; }
            int b = hit(x, y, race);
            if (f->btn == B_COIN) {            /* slid off the coin: highlight the fan item under the finger */
                fan_hover = (b >= 0 && btns[b].kind == 2) ? b : -1;
                return;
            }
            if (f->btn >= 0 && btns[f->btn].kind == 2) return;
            /* sliding a finger between buttons (e.g. steer left -> right) */
            if (b != f->btn && b >= 0 && btns[b].race_only && btns[b].kind == 0) {
                if (b == f->btn2) { f->btn2 = f->btn; f->btn = b; }        /* slid onto the chord partner: keep both */
                else { press(f->btn, 0); f->btn = b; press(b, 1); }
            }
            if (f->btn >= 0) set_chord(f, chord_of(f->btn, x, y));
            else if (b < 0 && f->btn >= 0) {
                float dx = x - btns[f->btn].x, dy = y - btns[f->btn].y;
                if (sqrtf(dx * dx + dy * dy) > btns[f->btn].r * 2.0f) { set_chord(f, -1); press(f->btn, 0); f->btn = -1; }
            }
        } else { /* up */
            if (f->mouse && glide_to_game(e->tfinger.x, e->tfinger.y, &gx, &gy)) user32_mouse_event(gx, gy, 0, 2);
            if (f->btn == B_COIN && fan_hover >= 0) {   /* hold coin, slide, release: buy */
                press(fan_hover, 1); press(fan_hover, 0);   /* a quick tap is held until the game polls */
                fan_open = 0;
            } else if (f->btn == B_COIN) fan_until = SDL_GetTicks() + 3000;
            fan_hover = -1;
            set_chord(f, -1);
            press(f->btn, 0);
            f->active = 0; f->btn = -1; f->mouse = 0;
        }
    }
}

static int fan_hover_held(void) {
    for (int i = 0; i < 10; i++) if (fingers[i].active && (fingers[i].btn == B_COIN || (fingers[i].btn >= 0 && btns[fingers[i].btn].kind == 2))) return 1;
    return 0;
}

/* drop held buttons when switching between menus and races */
void touch_tick(void) {
    static int last_race = -1;
    int race = in_race();
    if (fan_open && !fan_hover_held() && SDL_TICKS_PASSED(SDL_GetTicks(), fan_until)) fan_open = 0;
    if (!race) fan_open = 0;
    if (fan_force && race) fan_open = 1;
    if (race != last_race) {
        for (int i = 0; i < 10; i++) if (fingers[i].active && fingers[i].btn >= 0 && btns[fingers[i].btn].race_only && !race) {
            if (fingers[i].btn2 >= 0) { press(fingers[i].btn2, 0); fingers[i].btn2 = -1; }
            press(fingers[i].btn, 0); fingers[i].btn = -1;
        }
        last_race = race;
    }
}
void touch_sensor(const float *d) { (void)d; }

/* ---------------- drawing ---------------- */
static const char *VS = "#version 300 es\nlayout(location=0) in vec2 p; layout(location=1) in vec4 c; uniform vec2 sc; out vec4 vc; void main(){ vc=c; gl_Position=vec4(p.x*sc.x-1.0, 1.0-p.y*sc.y, 0.0, 1.0); }\n";
static const char *FS = "#version 300 es\nprecision mediump float; in vec4 vc; out vec4 o; void main(){ o=vc; }\n";

/* textured buttons: premultiplied atlas, vertex = x y u v alpha */
static const char *VS_T = "#version 300 es\nlayout(location=0) in vec2 p; layout(location=1) in vec3 t; uniform vec2 sc; out vec3 vt; void main(){ vt=t; gl_Position=vec4(p.x*sc.x-1.0, 1.0-p.y*sc.y, 0.0, 1.0); }\n";
static const char *FS_T = "#version 300 es\nprecision mediump float; uniform sampler2D tex; in vec3 vt; out vec4 o; void main(){ o=texture(tex, vt.xy)*vt.z; }\n";
static GLuint prog_t, vbo_t, vao_t, tex_atlas;
static GLint u_sc_t;
static float tb[NB * 6 * 5]; static int ntb;

static GLuint sh(GLenum t, const char *s) { GLuint x = glCreateShader(t); glShaderSource(x, 1, &s, NULL); glCompileShader(x); return x; }
static float vb[4096]; static int nvb;
static void tri(float ax, float ay, float bx, float by, float cx, float cy) {
    if (nvb + 6 > 4096) return;
    vb[nvb++] = ax; vb[nvb++] = ay; vb[nvb++] = bx; vb[nvb++] = by; vb[nvb++] = cx; vb[nvb++] = cy;
}
static void quad(float x0, float y0, float x1, float y1) { tri(x0, y0, x1, y0, x0, y1); tri(x1, y0, x1, y1, x0, y1); }
static void disc(float x, float y, float r, float r0) {
    for (int i = 0; i < 40; i++) {
        float a0 = i * 6.2831853f / 40, a1 = (i + 1) * 6.2831853f / 40;
        float c0 = cosf(a0), s0 = sinf(a0), c1 = cosf(a1), s1 = sinf(a1);
        tri(x + c0 * r0, y + s0 * r0, x + c0 * r, y + s0 * r, x + c1 * r, y + s1 * r);
        if (r0 > 0) tri(x + c0 * r0, y + s0 * r0, x + c1 * r, y + s1 * r, x + c1 * r0, y + s1 * r0);
    }
}
/* all shapes go into one coloured batch, drawn with a single call per frame */
static float batch[32768]; static int nbatch;
static void flushdraw(float r, float g, float b, float a) {
    for (int i = 0; i + 1 < nvb && nbatch + 6 <= (int)(sizeof batch / sizeof *batch); i += 2) {
        float *d = batch + nbatch;
        d[0] = vb[i]; d[1] = vb[i + 1]; d[2] = r; d[3] = g; d[4] = b; d[5] = a;
        nbatch += 6;
    }
    nvb = 0;
}
/* 3x5 pixel font for the readout: each glyph is 5 rows of 3 bits */
static const char *FONT_CH = "0123456789.FPSGAMEWLC:UNIT";
static const unsigned char FONT[][5] = {
    {7,5,5,5,7},{2,6,2,2,7},{7,1,7,4,7},{7,1,7,1,7},{5,5,7,1,1},{7,4,7,1,7},{7,4,7,5,7},{7,1,1,1,1},{7,5,7,5,7},{7,5,7,1,7},
    {0,0,0,0,2},{7,4,6,4,4},{7,5,7,4,4},{7,4,7,1,7},{7,4,5,5,7},{7,5,7,5,5},{5,7,7,5,5},{7,4,6,4,7},{5,5,7,7,5},{4,4,4,4,7},
    {7,4,4,4,7},{0,2,0,2,0},{5,5,5,5,7},{5,7,7,7,5},{7,2,2,2,7},{7,2,2,2,2},
};
static void text(float x, float y, float px, const char *str) {
    for (const char *c = str; *c; c++, x += px * 4) {
        const char *f = strchr(FONT_CH, *c);
        if (!f || !*c) continue;
        const unsigned char *g = FONT[f - FONT_CH];
        for (int r = 0; r < 5; r++) for (int b = 0; b < 3; b++)
            if (g[r] & (4 >> b)) quad(x + b * px, y + r * px, x + (b + 1) * px, y + (r + 1) * px);
    }
}

static void atlas_init(void) {
    uLongf n = (uLongf)TA_W * TA_H * 4;
    unsigned char *px = malloc(n);
    if (!px || uncompress(px, &n, ta_zlib, sizeof ta_zlib) != Z_OK) { LOG("touch: atlas decode failed"); free(px); return; }
    for (uLongf i = 0; i < n; i += 4) {    /* premultiply alpha: clean edges with mipmaps */
        unsigned a = px[i + 3];
        px[i] = px[i] * a / 255; px[i + 1] = px[i + 1] * a / 255; px[i + 2] = px[i + 2] * a / 255;
    }
    glGenTextures(1, &tex_atlas);
    glBindTexture(GL_TEXTURE_2D, tex_atlas);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, TA_W, TA_H, 0, GL_RGBA, GL_UNSIGNED_BYTE, px);
    glGenerateMipmap(GL_TEXTURE_2D);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR_MIPMAP_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    free(px);
    prog_t = glCreateProgram();
    glAttachShader(prog_t, sh(GL_VERTEX_SHADER, VS_T)); glAttachShader(prog_t, sh(GL_FRAGMENT_SHADER, FS_T));
    glLinkProgram(prog_t);
    u_sc_t = glGetUniformLocation(prog_t, "sc");
    glGenVertexArrays(1, &vao_t); glGenBuffers(1, &vbo_t);
    glBindVertexArray(vao_t); glBindBuffer(GL_ARRAY_BUFFER, vbo_t);
    glEnableVertexAttribArray(0); glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 20, 0);
    glEnableVertexAttribArray(1); glVertexAttribPointer(1, 3, GL_FLOAT, GL_FALSE, 20, (void *)8);
}

/* one button sprite: the hexagon (radius TA_FRAME_R of half a cell) covers the button's radius */
static void sprite(const Btn *b, float scale, float alpha) {
    if (ntb + 30 > (int)(sizeof tb / sizeof *tb)) return;
    float h = b->r * scale / TA_FRAME_R;
    int cx = b->art % TA_COLS, cy = b->art / TA_COLS;
    float u0 = (float)(cx * TA_CELL) / TA_W, v0 = (float)(cy * TA_CELL) / TA_H;
    float u1 = u0 + (float)TA_CELL / TA_W, v1 = v0 + (float)TA_CELL / TA_H;
    float q[4][4] = {{b->x - h, b->y - h, u0, v0}, {b->x + h, b->y - h, u1, v0}, {b->x - h, b->y + h, u0, v1}, {b->x + h, b->y + h, u1, v1}};
    static const int idx[6] = {0, 1, 2, 1, 3, 2};
    for (int i = 0; i < 6; i++) {
        float *d = tb + ntb; const float *v = q[idx[i]];
        d[0] = v[0]; d[1] = v[1]; d[2] = v[2]; d[3] = v[3]; d[4] = alpha;
        ntb += 5;
    }
}

void touch_draw(void) {
    if (!visible && !perf_on) return;
    if (!prog) {
        prog = glCreateProgram();
        glAttachShader(prog, sh(GL_VERTEX_SHADER, VS)); glAttachShader(prog, sh(GL_FRAGMENT_SHADER, FS));
        glLinkProgram(prog);
        u_sc = glGetUniformLocation(prog, "sc");
        glGenVertexArrays(1, &vao); glGenBuffers(1, &vbo);
        glBindVertexArray(vao); glBindBuffer(GL_ARRAY_BUFFER, vbo);
        glEnableVertexAttribArray(0); glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 24, 0);
        glEnableVertexAttribArray(1); glVertexAttribPointer(1, 4, GL_FLOAT, GL_FALSE, 24, (void *)8);
    }
    layout();
    int w, h; plat_drawable_size(&w, &h);
    glBindFramebuffer(GL_FRAMEBUFFER, 0);
    glViewport(0, 0, w, h);
    glDisable(GL_DEPTH_TEST); glDisable(GL_CULL_FACE);
    glEnable(GL_BLEND); glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glColorMask(1, 1, 1, 1);
    glUseProgram(prog);
    glBindVertexArray(vao); glBindBuffer(GL_ARRAY_BUFFER, vbo);
    glUniform2f(u_sc, 2.0f / scr_a, 2.0f);
    int race = in_race();
    if (perf_on) {
        float fps, game, gl, sw; glide_perf(&fps, &game, &gl, &sw);
        char line[96];
        char cap[16]; if (plat_fps_cap()) snprintf(cap, sizeof cap, "%d", plat_fps_cap()); else snprintf(cap, sizeof cap, "UNLIMIT");
        snprintf(line, sizeof line, "FPS %.0f  CAP %s  GAME %.1f  GL %.1f  SWAP %.1f", fps, cap, game, gl, sw);
        quad(0.01f, 0.005f, 0.01f + strlen(line) * 0.016f + 0.01f, 0.06f); flushdraw(0, 0, 0, 0.6f);
        text(0.02f, 0.015f, 0.008f, line); flushdraw(1, 1, 0.3f, 1);
    }
    if (nbatch) {
        glBufferData(GL_ARRAY_BUFFER, nbatch * 4, batch, GL_STREAM_DRAW);
        glDrawArrays(GL_TRIANGLES, 0, nbatch / 6);
        nbatch = 0;
    }
    if (visible && !pad_mode) {
        if (!prog_t) atlas_init();
        if (tex_atlas) {
            for (int i = 0; i < NB; i++) {
                const Btn *b = &btns[i];
                if (b->race_only && !race) continue;
                if (b->kind == 2 && !fan_open) continue;
                int on = held[i] || (i == B_COIN && fan_open) || i == fan_hover;
                sprite(b, on ? 1.1f : 1.0f, on ? 0.95f : (b->kind == 2 ? 0.9f : 0.62f));
            }
            glUseProgram(prog_t);
            glUniform2f(u_sc_t, 2.0f / scr_a, 2.0f);
            glActiveTexture(GL_TEXTURE0);
            glBindTexture(GL_TEXTURE_2D, tex_atlas);
            glBlendFunc(GL_ONE, GL_ONE_MINUS_SRC_ALPHA);
            glBindVertexArray(vao_t); glBindBuffer(GL_ARRAY_BUFFER, vbo_t);
            glBufferData(GL_ARRAY_BUFFER, ntb * 4, tb, GL_STREAM_DRAW);
            glDrawArrays(GL_TRIANGLES, 0, ntb / 5);
            ntb = 0;
        }
    }
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glDisable(GL_BLEND);
}
